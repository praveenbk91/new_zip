CREATE OR REPLACE VIEW AIM_ANA_ASSET_PHYSICAL_LIFE
AS
SELECT
  A.MULTITENANT_ID,
  A.ASSET_TAG,
  A.COST_MODEL,
  COALESCE(P.CLIMATE_ZONE, COALESCE(F.CLIMATE_ZONE, R.CLIMATE_ZONE)) AS CLIMATE_ZONE,
  COALESCE(C.PHYSICAL_LIFE, M.PHYSICAL_LIFE) AS PHYSICAL_LIFE,
  (SELECT COALESCE(SUM(H.PHYSICAL_LIFE_ADJ),0)
     FROM AE_ANA_AST_PHY_LIFE_HIST H
     WHERE A.ASSET_TAG = H.ASSET_TAG AND A.MULTITENANT_ID = H.MULTITENANT_ID) AS PHYSICAL_LIFE_ADJ
FROM
  AE_A_ASSET_E A
  INNER JOIN AE_B_REG_E R ON A.REGION_CODE = R.REGION_CODE
    AND A.MULTITENANT_ID = R.MULTITENANT_ID
  INNER JOIN AE_B_FAC_E F ON A.REGION_CODE = F.REGION_CODE
    AND A.FAC_ID = F.FAC_ID
    AND A.MULTITENANT_ID = F.MULTITENANT_ID
  INNER JOIN AE_S_BLD_C P ON A.REGION_CODE = P.REGION_CODE
    AND A.FAC_ID = P.FAC_ID
    AND A.BLDG = P.BLDG
    AND A.MULTITENANT_ID = P.MULTITENANT_ID
  INNER JOIN AE_ANA_COST_MODEL M ON A.COST_MODEL = M.COST_MODEL
    AND A.MULTITENANT_ID = M.MULTITENANT_ID
  LEFT OUTER JOIN AE_ANA_COST_MODEL_CLIMATE C ON M.COST_MODEL = C.COST_MODEL
    AND COALESCE(P.CLIMATE_ZONE, COALESCE(F.CLIMATE_ZONE, R.CLIMATE_ZONE)) = C.CLIMATE_ZONE
    AND M.MULTITENANT_ID = C.MULTITENANT_ID
;

