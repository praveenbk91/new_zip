INSERT INTO AIM_PHASE_COST (
  MULTITENANT_ID, PROPOSAL, SORT_CODE,
  EST_LABOR, EST_MATERIAL, EST_EQUIPMENT, EST_CONTRACT, EST_HOURS,
  ENC_LABOR, ENC_MATERIAL, ENC_EQUIPMENT, ENC_CONTRACT,
  ALLOC_EXP_LABOR, ALLOC_EXP_MATERIAL, ALLOC_EXP_EQUIPMENT, ALLOC_EXP_CONTRACT,
  UNALLOC_EXP_LABOR, UNALLOC_EXP_MATERIAL, UNALLOC_EXP_EQUIPMENT, UNALLOC_EXP_CONTRACT,
  ACTUAL_HOURS,
  BILLED_LABOR, BILLED_MATERIAL, BILLED_EQUIPMENT, BILLED_CONTRACT)
SELECT
  A.MULTITENANT_ID,
  A.PROPOSAL,
  A.SORT_CODE,
  ROUND(COALESCE(A.TOT_LAB,0.00),2) AS EST_LABOR,
  ROUND(COALESCE(A.TOT_MAT,0.00),2) AS EST_MATERIAL,
  ROUND(COALESCE(A.TOT_EQP,0.00),2) AS EST_EQUIPMENT,
  ROUND(COALESCE(A.TOT_OTH,0.00),2) AS EST_CONTRACT,
  COALESCE(A.TOT_HRS,0.00) AS EST_HOURS,
  COALESCE(B.ENC_LABOR,0.00) AS ENC_LABOR,
  COALESCE(B.ENC_MATERIAL,0.00) AS ENC_MATERIAL,
  COALESCE(B.ENC_EQUIPMENT,0.00) AS ENC_EQUIPMENT,
  COALESCE(B.ENC_CONTRACT,0.00) AS ENC_CONTRACT,
  COALESCE(B.ACTUAL_LABOR,0.00) AS ALLOC_EXP_LABOR,
  COALESCE(B.ACTUAL_MATERIAL,0.00) AS ALLOC_EXP_MATERIAL,
  COALESCE(B.ACTUAL_EQUIPMENT,0.00) AS ALLOC_EXP_EQUIPMENT,
  COALESCE(B.ACTUAL_CONTRACT,0.00) AS ALLOC_EXP_CONTRACT,
  COALESCE(E.UNALLOC_EXP_LABOR,0.00) AS UNALLOC_EXP_LABOR,
  COALESCE(E.UNALLOC_EXP_MATERIAL,0.00) AS UNALLOC_EXP_MATERIAL,
  COALESCE(E.UNALLOC_EXP_EQUIPMENT,0.00) AS UNALLOC_EXP_EQUIPMENT,
  COALESCE(E.UNALLOC_EXP_CONTRACT,0.00) AS UNALLOC_EXP_CONTRACT,
  COALESCE(D.ACTUAL_HOURS,0.00) AS ACTUAL_HOURS,
  ROUND(CASE WHEN C.FND_API_COUNT < 1 THEN COALESCE(B.BILLED_LABOR,0.00) ELSE 0.0 END
    + COALESCE(F.BILLED_LABOR,0.00) + COALESCE(G.BILLED_LABOR,0.00),2) AS BILLED_LABOR,
  ROUND(CASE WHEN C.FND_API_COUNT < 1 THEN COALESCE(B.BILLED_MATERIAL,0.00) ELSE 0.0 END
    + COALESCE(F.BILLED_MATERIAL,0.00) + COALESCE(G.BILLED_MATERIAL,0.00),2) AS BILLED_MATERIAL,
  ROUND(CASE WHEN C.FND_API_COUNT < 1 THEN COALESCE(B.BILLED_EQUIPMENT,0.00) ELSE 0.0 END
    + COALESCE(F.BILLED_EQUIPMENT,0.00) + COALESCE(G.BILLED_EQUIPMENT,0.00),2) AS BILLED_EQUIPMENT,
  ROUND(CASE WHEN C.FND_API_COUNT < 1 THEN COALESCE(B.BILLED_CONTRACT,0.00) ELSE 0.0 END
    + COALESCE(F.BILLED_CONTRACT,0.00) + COALESCE(G.BILLED_CONTRACT,0.00),2) AS BILLED_CONTRACT
FROM
  AE_P_PHS_E A
  LEFT OUTER JOIN (
    SELECT
      C.MULTITENANT_ID,
      C.PROPOSAL,
      C.SORT_CODE,
      SUM(CASE WHEN C.FIN_TYPE = 'E' AND C.SUBLEDGER_TYPE = 'L' THEN COALESCE(C.AMOUNT,0.00) ELSE 0.00 END) AS ENC_LABOR,
      SUM(CASE WHEN C.FIN_TYPE = 'E' AND C.SUBLEDGER_TYPE = 'M' THEN COALESCE(C.AMOUNT,0.00) ELSE 0.00 END) AS ENC_MATERIAL,
      SUM(CASE WHEN C.FIN_TYPE = 'E' AND C.SUBLEDGER_TYPE = 'E' THEN COALESCE(C.AMOUNT,0.00) ELSE 0.00 END) AS ENC_EQUIPMENT,
      SUM(CASE WHEN C.FIN_TYPE = 'E' AND C.SUBLEDGER_TYPE = 'C' THEN COALESCE(C.AMOUNT,0.00) ELSE 0.00 END) AS ENC_CONTRACT,
      SUM(CASE WHEN C.FIN_TYPE = 'A' AND C.SUBLEDGER_TYPE = 'L' THEN COALESCE(C.AMOUNT,0.00) ELSE 0.00 END) AS ACTUAL_LABOR,
      SUM(CASE WHEN C.FIN_TYPE = 'A' AND C.SUBLEDGER_TYPE = 'M' THEN COALESCE(C.AMOUNT,0.00) ELSE 0.00 END) AS ACTUAL_MATERIAL,
      SUM(CASE WHEN C.FIN_TYPE = 'A' AND C.SUBLEDGER_TYPE = 'E' THEN COALESCE(C.AMOUNT,0.00) ELSE 0.00 END) AS ACTUAL_EQUIPMENT,
      SUM(CASE WHEN C.FIN_TYPE = 'A' AND C.SUBLEDGER_TYPE = 'C' THEN COALESCE(C.AMOUNT,0.00) ELSE 0.00 END) AS ACTUAL_CONTRACT,
      SUM(CASE WHEN C.FIN_TYPE = 'A' AND C.BILL_DATE IS NOT NULL AND (C.BILL_SEQ IS NULL OR C.BILL_SEQ = 0) AND C.SUBLEDGER_TYPE = 'L'
        THEN COALESCE(C.BILL_AMOUNT,COALESCE(C.AMOUNT,0.00))
        ELSE 0.00 END) AS BILLED_LABOR,
      SUM(CASE WHEN C.FIN_TYPE = 'A' AND C.BILL_DATE IS NOT NULL AND (C.BILL_SEQ IS NULL OR C.BILL_SEQ = 0) AND C.SUBLEDGER_TYPE = 'M'
        THEN COALESCE(C.BILL_AMOUNT,COALESCE(C.AMOUNT,0.00))
        ELSE 0.00 END) AS BILLED_MATERIAL,
      SUM(CASE WHEN C.FIN_TYPE = 'A' AND C.BILL_DATE IS NOT NULL AND (C.BILL_SEQ IS NULL OR C.BILL_SEQ = 0) AND C.SUBLEDGER_TYPE = 'E'
        THEN COALESCE(C.BILL_AMOUNT,COALESCE(C.AMOUNT,0.00))
        ELSE 0.00 END) AS BILLED_EQUIPMENT,
      SUM(CASE WHEN C.FIN_TYPE = 'A' AND C.BILL_DATE IS NOT NULL AND (C.BILL_SEQ IS NULL OR C.BILL_SEQ = 0) AND C.SUBLEDGER_TYPE = 'C'
        THEN COALESCE(C.BILL_AMOUNT,COALESCE(C.AMOUNT,0.00))
        ELSE 0.00 END) AS BILLED_CONTRACT
    FROM
      AE_S_FND_A C
    WHERE
      C.PROPOSAL IS NOT NULL
        AND C.SORT_CODE IS NOT NULL
        AND C.FIN_TYPE IN ('E','A')
    GROUP BY
      C.MULTITENANT_ID,
      C.PROPOSAL,
      C.SORT_CODE
  ) B ON A.MULTITENANT_ID = B.MULTITENANT_ID
   AND A.PROPOSAL = B.PROPOSAL
   AND A.SORT_CODE = B.SORT_CODE
  LEFT OUTER JOIN (
    SELECT
      A.MULTITENANT_ID,
      A.PROPOSAL,
      A.SORT_CODE,
      SUM(ROUND(COALESCE(A.ACT_HRS,0.00),2)) AS ACTUAL_HOURS
    FROM
      AE_P_WKA_D A,
      AE_P_LAT_C B
    WHERE
      A.MULTITENANT_ID = B.MULTITENANT_ID
        AND A.TIME_TYPE = B.TIME_TYPE
        AND A.TIME_TYPE IS NOT NULL
        AND A.PROPOSAL IS NOT NULL
        AND A.SORT_CODE IS NOT NULL
        AND A.APPROVAL_DATE IS NOT NULL
        AND B.POST_HOURS = 'Y'
    GROUP BY
      A.MULTITENANT_ID,
      A.PROPOSAL,
      A.SORT_CODE
