/* * * * * * * * * * * * * * * * * * * *
*  Drop any remaining materialized view objects
* * * * * * * * * * * * * * * * * * * */
DECLARE
  CURSOR c1 IS
    SELECT TABLE_NAME
      FROM USER_TABLES
      WHERE (TABLE_NAME LIKE 'MLOG$_AE_%' OR TABLE_NAME LIKE 'MLOG$_AIM_%' OR TABLE_NAME LIKE 'AIM_%')
      ORDER BY TABLE_NAME;
BEGIN
  FOR r1 IN c1 LOOP
    IF r1.TABLE_NAME LIKE 'AIM_%' THEN
      DROP_TABLE_VIEW(r1.TABLE_NAME);
    ELSE
      DROP_TABLE_VIEW_LOG(r1.TABLE_NAME);
    END IF;
  END LOOP;
END;
/

DROP PROCEDURE DROP_TABLE_VIEW;
DROP PROCEDURE DROP_TABLE_VIEW_LOG;

