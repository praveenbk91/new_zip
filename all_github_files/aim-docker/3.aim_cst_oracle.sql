CREATE OR REPLACE VIEW AIM_PO_ANT_LIST
AS
SELECT
  C.MULTITENANT_ID,
  C.CAPITAL_PROJECT,
  C.COMPONENT_ID,
  C.COMPONENT,
  E.COMPONENT_GROUP,
  C.EDIT_DATE AS TRANS_DATE,
  C.PO_CODE AS TRANS_NO,
  CAST(B.PO_ITEM AS CHAR) AS LINE_ITEM,
  CAST(C.SEQ AS CHAR) AS SUB_LINE_ITEM,
  B.VEND_DSC AS DESCRIPTION,
  '' AS CONTRACT_NO,
  A.CONTRACTOR,
  'PURCHASE ORDER' AS TRANX_TYPE,
  CASE WHEN B.INVENTORY_FLAG = 'S' THEN COALESCE(C.LINE_AMOUNT, 0.0) ELSE COALESCE(B.VEND_COST, 0.0) * COALESCE(C.ITEM_QTY, 0.0) END
      - COALESCE(C.DISCOUNT_AMT,0.0)
      + COALESCE(C.TAX1_AMT,0.0)
      + COALESCE(C.TAX2_AMT,0.0)
      - COALESCE(C.TAX_REBATE_AMT,0.0)
      + COALESCE(C.SHIP_AMT,0.0)
      + COALESCE(C.MARKUP_AMT,0.0) AS AMOUNT
FROM
  AE_I_POE_E A
  INNER JOIN AE_I_POE_D B ON A.PO_CODE = B.PO_CODE
    AND A.MULTITENANT_ID = B.MULTITENANT_ID
  INNER JOIN AE_I_POE_P C ON B.PO_CODE = C.PO_CODE
    AND B.PO_ITEM = C.PO_ITEM
    AND B.MULTITENANT_ID = C.MULTITENANT_ID
  INNER JOIN AE_I_POE_STATUS_E D ON A.PO_TYPE = D.PO_TYPE
    AND A.STATUS_CODE = D.STATUS_CODE
    AND A.MULTITENANT_ID = D.MULTITENANT_ID
  INNER JOIN AE_CP_PRJ_COMP E ON C.CAPITAL_PROJECT = E.CAPITAL_PROJECT
    AND C.COMPONENT_ID = E.COMPONENT_ID
    AND C.MULTITENANT_ID = E.MULTITENANT_ID
  LEFT OUTER JOIN AE_P_PHS_E F ON C.PROPOSAL = F.PROPOSAL
		AND C.SORT_CODE = F.SORT_CODE
		AND C.MULTITENANT_ID = F.MULTITENANT_ID
WHERE
  C.CAPITAL_PROJECT IS NOT NULL
    AND C.COMPONENT_ID IS NOT NULL
    AND (B.INVENTORY_FLAG = 'S' AND C.LINE_AMOUNT IS NOT NULL
      OR B.INVENTORY_FLAG <> 'S' AND B.VEND_COST IS NOT NULL AND C.ITEM_QTY IS NOT NULL)
    AND D.COMPLETE_YN = 'O'
    AND (C.SORT_CODE IS NULL OR F.CONTRACT_TYPE <> 'I');

