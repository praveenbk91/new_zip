*  Drop tables, views and materialized views
* * * * * * * * * * * * * * * * * * * */
CREATE OR REPLACE PROCEDURE DROP_TABLE_VIEW(entity_name USER_TABLES.TABLE_NAME%TYPE)
AS
  v_entity_name USER_TABLES.TABLE_NAME%TYPE;
  v_num_rows NUMBER(5,0);
BEGIN
  v_entity_name := SUBSTR(entity_name,1,30);
  SELECT COUNT(*) INTO v_num_rows FROM USER_MVIEW_LOGS WHERE MASTER = v_entity_name;
  IF v_num_rows > 0 THEN EXECUTE IMMEDIATE 'DROP MATERIALIZED VIEW LOG ON ' || v_entity_name; END IF;
  SELECT COUNT(*) INTO v_num_rows FROM USER_MVIEWS WHERE MVIEW_NAME = v_entity_name;
  IF v_num_rows > 0 THEN EXECUTE IMMEDIATE 'DROP MATERIALIZED VIEW ' || v_entity_name; END IF;
  SELECT COUNT(*) INTO v_num_rows FROM USER_VIEWS WHERE VIEW_NAME = v_entity_name;
  IF v_num_rows > 0 THEN EXECUTE IMMEDIATE 'DROP VIEW ' || v_entity_name; END IF;
  SELECT COUNT(*) INTO v_num_rows FROM USER_TABLES WHERE TABLE_NAME = v_entity_name;
  IF v_num_rows > 0 THEN EXECUTE IMMEDIATE 'DROP TABLE ' || v_entity_name; END IF;
END;
/

