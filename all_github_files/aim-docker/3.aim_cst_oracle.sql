/* AIM_TIMECARD_TOTALS - Begin */
CREATE TABLE AIM_TIMECARD_TOTALS
(
  MULTITENANT_ID         NUMBER(8,0)    DEFAULT 1   NOT NULL,
  TRANS_NO               NUMBER(8,0)                NOT NULL,
  SHOP_PERSON            VARCHAR2(25)               NOT NULL,
  WORK_DATE              DATE                       NOT NULL,
  POSTED                 VARCHAR2(1),
  SHOP_CAPACITY_HOURS    NUMBER(4,2),
  EMPLOYEE_SCHED_HOURS   NUMBER(4,2),
  TRADE_CAPACITY_HOURS   NUMBER(4,2),
  WORK_HOURS             NUMBER(6,2),
  REGULAR_HOURS          NUMBER(6,2),
  OT_HOURS               NUMBER(6,2),
  DIFF_HOURS             NUMBER(6,2),
  LEAVE_HOURS            NUMBER(6,2),
  TOTAL_HOURS            NUMBER(6,2),
  TOTAL_COST             NUMBER(12,4),
  CONSTRAINT PK_AIM_TIMECARD_TOTALS PRIMARY KEY (TRANS_NO, MULTITENANT_ID)
);

INSERT INTO AIM_TIMECARD_TOTALS (
  MULTITENANT_ID, TRANS_NO, SHOP_PERSON, WORK_DATE, POSTED,
  SHOP_CAPACITY_HOURS, EMPLOYEE_SCHED_HOURS, TRADE_CAPACITY_HOURS,
  WORK_HOURS, REGULAR_HOURS, OT_HOURS, DIFF_HOURS, LEAVE_HOURS,
  TOTAL_HOURS, TOTAL_COST)
SELECT
  TC.MULTITENANT_ID,
  TC.TRANS_NO,
  TC.SHOP_PERSON,
  TC.SCHED_DATE AS WORK_DATE,
  TC.POST_FLAG AS POSTED,
  ROUND(CASE
    WHEN TO_NUMBER(TO_CHAR(TC.SCHED_DATE, 'D')) = 1 THEN COALESCE(SUM(SHP.SUN_CAPACITY) / COUNT(*), 0.0)
    WHEN TO_NUMBER(TO_CHAR(TC.SCHED_DATE, 'D')) = 2 THEN COALESCE(SUM(SHP.MON_CAPACITY) / COUNT(*), 0.0)
    WHEN TO_NUMBER(TO_CHAR(TC.SCHED_DATE, 'D')) = 3 THEN COALESCE(SUM(SHP.TUE_CAPACITY) / COUNT(*), 0.0)
    WHEN TO_NUMBER(TO_CHAR(TC.SCHED_DATE, 'D')) = 4 THEN COALESCE(SUM(SHP.WED_CAPACITY) / COUNT(*), 0.0)
    WHEN TO_NUMBER(TO_CHAR(TC.SCHED_DATE, 'D')) = 5 THEN COALESCE(SUM(SHP.THU_CAPACITY) / COUNT(*), 0.0)
    WHEN TO_NUMBER(TO_CHAR(TC.SCHED_DATE, 'D')) = 6 THEN COALESCE(SUM(SHP.FRI_CAPACITY) / COUNT(*), 0.0)
    WHEN TO_NUMBER(TO_CHAR(TC.SCHED_DATE, 'D')) = 7 THEN COALESCE(SUM(SHP.SAT_CAPACITY) / COUNT(*), 0.0) END, 2) AS SHOP_CAPACITY_HOURS,
  COALESCE(EXC.SCHED_HOURS, REG.SCHED_HOURS, 0.0) AS EMPLOYEE_SCHED_HOURS,
  COALESCE(TRD.DAILY_HOURS, 0.0) AS TRADE_CAPACITY_HOURS,
  COALESCE(TOT.WORK_HOURS, 0.0) AS WORK_HOURS,
  COALESCE(TOT.REGULAR_HOURS, 0.0) AS REGULAR_HOURS,
  COALESCE(TOT.OT_HOURS, 0.0) AS OT_HOURS,
  COALESCE(TOT.DIFF_HOURS, 0.0) AS DIFF_HOURS,
  COALESCE(TOT.LEAVE_HOURS, 0.0) AS LEAVE_HOURS,
  COALESCE(TOT.TOTAL_HOURS, 0.0) AS TOTAL_HOURS,
  COALESCE(TOT.TOTAL_COST, 0.0) AS TOTAL_COST
FROM
  AE_P_WKA_E TC
  LEFT JOIN (
    SELECT
      AE_L_SHP_E.MULTITENANT_ID,
      AE_L_SHP_E.SHOP,
      AE_L_SHP_D.SHOP_PERSON,
      COALESCE(AE_L_SHP_E.SUN_CAPACITY, 0.0) AS SUN_CAPACITY,
      COALESCE(AE_L_SHP_E.MON_CAPACITY, 0.0) AS MON_CAPACITY,
      COALESCE(AE_L_SHP_E.TUE_CAPACITY, 0.0) AS TUE_CAPACITY,
      COALESCE(AE_L_SHP_E.WED_CAPACITY, 0.0) AS WED_CAPACITY,
      COALESCE(AE_L_SHP_E.THU_CAPACITY, 0.0) AS THU_CAPACITY,
      COALESCE(AE_L_SHP_E.FRI_CAPACITY, 0.0) AS FRI_CAPACITY,
      COALESCE(AE_L_SHP_E.SAT_CAPACITY, 0.0) AS SAT_CAPACITY,
      AE_L_SHP_D.DATE_FROM,
      AE_L_SHP_D.DATE_TO
    FROM
      AE_L_SHP_E
      INNER JOIN AE_L_SHP_D ON AE_L_SHP_E.SHOP = AE_L_SHP_D.SHOP
        AND AE_L_SHP_E.MULTITENANT_ID = AE_L_SHP_D.MULTITENANT_ID
    WHERE
      AE_L_SHP_E.ACTIVE = 'Y'
  ) SHP ON TC.SHOP_PERSON = SHP.SHOP_PERSON
    AND (SHP.DATE_FROM IS NULL OR TRUNC(SHP.DATE_FROM) <= TRUNC(TC.SCHED_DATE))
    AND (SHP.DATE_TO IS NULL OR TRUNC(SHP.DATE_TO) >= TRUNC(TC.SCHED_DATE))
    AND TC.MULTITENANT_ID = SHP.MULTITENANT_ID
  LEFT JOIN (
    SELECT
      S.MULTITENANT_ID,
      S.SHOP_PERSON,
      S.WORK_DAY,
      CASE
        WHEN (LS.START_TIME < WS.START_TIME AND LS.END_TIME > WS.START_TIME AND LS.END_TIME < WS.END_TIME)
        THEN (TRUNC(WS.END_TIME / 100) + ROUND(MOD(WS.END_TIME, 100) / 60, 2)) -
            (TRUNC(LS.END_TIME / 100) + ROUND(MOD(LS.END_TIME, 100) / 60, 2))
        WHEN (LS.START_TIME > WS.START_TIME AND LS.START_TIME < WS.END_TIME AND LS.END_TIME > WS.END_TIME)
        THEN (TRUNC(LS.START_TIME / 100) + ROUND(MOD(LS.START_TIME, 100) / 60, 2)) -
            (TRUNC(WS.START_TIME / 100) + ROUND(MOD(WS.START_TIME, 100) / 60, 2))
        WHEN (LS.START_TIME < WS.START_TIME AND LS.END_TIME < WS.START_TIME) OR (LS.START_TIME > WS.END_TIME AND LS.END_TIME > WS.START_TIME)
        THEN (TRUNC(WS.END_TIME / 100) + ROUND(MOD(WS.END_TIME, 100) / 60, 2)) -
            (TRUNC(WS.START_TIME / 100) + ROUND(MOD(WS.START_TIME, 100) / 60, 2))
        WHEN (LS.START_TIME < WS.START_TIME AND LS.END_TIME > WS.END_TIME)
        THEN 0
        ELSE (TRUNC(WS.END_TIME / 100) + ROUND(MOD(WS.END_TIME, 100) / 60, 2)) -
            (TRUNC(WS.START_TIME / 100) + ROUND(MOD(WS.START_TIME, 100) / 60, 2)) -
            (TRUNC(LS.END_TIME / 100) + ROUND(MOD(LS.END_TIME, 100) / 60, 2)) -
            (TRUNC(LS.START_TIME / 100) + ROUND(MOD(LS.START_TIME, 100) / 60, 2))
        END AS SCHED_HOURS
    FROM
      AE_H_SCH_D S
      INNER JOIN AE_H_SHF_C WS ON WS.SHIFT_TYPE = 'W'
        AND S.WORK_SHIFT_CODE = WS.SHIFT_CODE
        AND S.MULTITENANT_ID = WS.MULTITENANT_ID
      INNER JOIN AE_H_SHF_C LS ON LS.SHIFT_TYPE = 'L'
        AND S.LUNCH_SHIFT_CODE = LS.SHIFT_CODE
        AND S.MULTITENANT_ID = LS.MULTITENANT_ID
    WHERE
      S.FROM_DATE IS NULL
  ) REG ON TC.SHOP_PERSON = REG.SHOP_PERSON
    AND TO_NUMBER(TO_CHAR(TC.SCHED_DATE, 'D')) = REG.WORK_DAY
    AND TC.MULTITENANT_ID = REG.MULTITENANT_ID
  LEFT JOIN (
    SELECT
      S.MULTITENANT_ID,
      S.SHOP_PERSON,
      S.WORK_DAY,
      S.FROM_DATE,
      S.TO_DATE,
      CASE
        WHEN (LS.START_TIME < WS.START_TIME AND LS.END_TIME > WS.START_TIME AND LS.END_TIME < WS.END_TIME)
        THEN (TRUNC(WS.END_TIME / 100) + ROUND(MOD(WS.END_TIME, 100) / 60, 2)) -
            (TRUNC(LS.END_TIME / 100) + ROUND(MOD(LS.END_TIME, 100) / 60, 2))
        WHEN (LS.START_TIME > WS.START_TIME AND LS.START_TIME < WS.END_TIME AND LS.END_TIME > WS.END_TIME)
        THEN (TRUNC(LS.START_TIME / 100) + ROUND(MOD(LS.START_TIME, 100) / 60, 2)) -
            (TRUNC(WS.START_TIME / 100) + ROUND(MOD(WS.START_TIME, 100) / 60, 2))
        WHEN (LS.START_TIME < WS.START_TIME AND LS.END_TIME < WS.START_TIME) OR (LS.START_TIME > WS.END_TIME AND LS.END_TIME > WS.START_TIME)
        THEN (TRUNC(WS.END_TIME / 100) + ROUND(MOD(WS.END_TIME, 100) / 60, 2)) -
            (TRUNC(WS.START_TIME / 100) + ROUND(MOD(WS.START_TIME, 100) / 60, 2))
        WHEN (LS.START_TIME < WS.START_TIME AND LS.END_TIME > WS.END_TIME)
        THEN 0
        ELSE (TRUNC(WS.END_TIME / 100) + ROUND(MOD(WS.END_TIME, 100) / 60, 2)) -
            (TRUNC(WS.START_TIME / 100) + ROUND(MOD(WS.START_TIME, 100) / 60, 2)) -
            (TRUNC(LS.END_TIME / 100) + ROUND(MOD(LS.END_TIME, 100) / 60, 2)) -
            (TRUNC(LS.START_TIME / 100) + ROUND(MOD(LS.START_TIME, 100) / 60, 2))
        END AS SCHED_HOURS
    FROM
      AE_H_SCH_D S
      INNER JOIN AE_H_SHF_C WS ON WS.SHIFT_TYPE = 'W'
        AND S.WORK_SHIFT_CODE = WS.SHIFT_CODE
        AND S.MULTITENANT_ID = WS.MULTITENANT_ID
      INNER JOIN AE_H_SHF_C LS ON LS.SHIFT_TYPE = 'L'
        AND S.LUNCH_SHIFT_CODE = LS.SHIFT_CODE
        AND S.MULTITENANT_ID = LS.MULTITENANT_ID
    WHERE
      S.FROM_DATE IS NOT NULL
  ) EXC ON TC.SHOP_PERSON = EXC.SHOP_PERSON
    AND TO_NUMBER(TO_CHAR(TC.SCHED_DATE, 'D')) = EXC.WORK_DAY
    AND TRUNC(EXC.FROM_DATE) <= TRUNC(TC.SCHED_DATE)
    AND (EXC.TO_DATE IS NULL OR TRUNC(EXC.TO_DATE) >= TRUNC(TC.SCHED_DATE))
    AND TC.MULTITENANT_ID = EXC.MULTITENANT_ID
  LEFT JOIN (
    SELECT
      MULTITENANT_ID,
      SHOP_PERSON,
      SUM(COALESCE(DAILY_HOURS, 0.0)) AS DAILY_HOURS
    FROM
      AE_H_EMP_TRADES_D
    WHERE
      DAILY_HOURS IS NOT NULL
    GROUP BY
      MULTITENANT_ID,
      SHOP_PERSON
  ) TRD ON TC.SHOP_PERSON = TRD.SHOP_PERSON
    AND TC.MULTITENANT_ID = TRD.MULTITENANT_ID
  LEFT JOIN (
    SELECT
      E.MULTITENANT_ID,
      E.TRANS_NO,
      SUM(CASE WHEN C.POST_HOURS = 'Y' THEN D.ACT_HRS ELSE 0.0 END) AS WORK_HOURS,
      SUM(CASE WHEN C.PAY_TYPE = 'R' THEN D.ACT_HRS ELSE 0.0 END) AS REGULAR_HOURS,
      SUM(CASE WHEN C.PAY_TYPE = 'O' THEN D.ACT_HRS ELSE 0.0 END) AS OT_HOURS,
      SUM(CASE WHEN C.PAY_TYPE = 'D' THEN D.ACT_HRS ELSE 0.0 END) AS DIFF_HOURS,
      SUM(CASE WHEN D.LEV_CODE IS NOT NULL THEN D.ACT_HRS ELSE 0.0 END) AS LEAVE_HOURS,
      SUM(CASE WHEN C.POST_HOURS = 'Y' OR D.LEV_CODE IS NOT NULL THEN D.ACT_HRS ELSE 0.0 END) AS TOTAL_HOURS,
      SUM(COALESCE(D.ACT_COST, 0.0)) AS TOTAL_COST
    FROM
      AE_P_WKA_E E
      INNER JOIN AE_P_WKA_D D ON E.TRANS_NO = D.TRANS_NO
        AND E.MULTITENANT_ID = D.MULTITENANT_ID
      LEFT JOIN AE_P_LAT_C C ON D.TIME_TYPE = C.TIME_TYPE
        AND D.MULTITENANT_ID = C.MULTITENANT_ID
    GROUP BY
      E.MULTITENANT_ID,
      E.TRANS_NO
  ) TOT ON TC.TRANS_NO = TOT.TRANS_NO
    AND TC.MULTITENANT_ID = TOT.MULTITENANT_ID
  GROUP BY
    TC.MULTITENANT_ID,
    TC.TRANS_NO,
    TC.SHOP_PERSON,
    TC.SCHED_DATE,
    TC.POST_FLAG,
    EXC.SCHED_HOURS,
    REG.SCHED_HOURS,
    TRD.DAILY_HOURS,
    TOT.WORK_HOURS,
    TOT.REGULAR_HOURS,
    TOT.OT_HOURS,
    TOT.DIFF_HOURS,
    TOT.LEAVE_HOURS,
    TOT.TOTAL_HOURS,
    TOT.TOTAL_COST;
/* AIM_TIMECARD_TOTALS - End */

