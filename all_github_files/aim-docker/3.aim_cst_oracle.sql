INSERT INTO AIM_INT_WORK_AGREE_COST (
  MULTITENANT_ID, AGREEMENT_NO, COMMITMENT, AMENDMENT, EXPENSED, PO_ENCUMBRANCE)
SELECT
  AE_CP_INT_WORK_AGREE.MULTITENANT_ID,
  AE_CP_INT_WORK_AGREE.AGREEMENT_NO,
  COALESCE(A.COMMITMENT, 0.0),
  COALESCE(B.AMENDMENT, 0.0),
  COALESCE(C.EXPENSED, 0.0),
  COALESCE(D.PO_ENCUMBRANCE, 0.0)
FROM
  AE_CP_INT_WORK_AGREE
  LEFT OUTER JOIN (
    SELECT
      MULTITENANT_ID,
      AGREEMENT_NO,
      SUM(COMMITMENT) AS COMMITMENT
    FROM
      AE_CP_INT_WORK_AGREE_D
    WHERE
      COMMITMENT IS NOT NULL
    GROUP BY
      MULTITENANT_ID,
      AGREEMENT_NO) A ON AE_CP_INT_WORK_AGREE.MULTITENANT_ID = A.MULTITENANT_ID
    AND AE_CP_INT_WORK_AGREE.AGREEMENT_NO = A.AGREEMENT_NO
  LEFT OUTER JOIN (
    SELECT
      MULTITENANT_ID,
      AGREEMENT_NO,
      SUM(AMOUNT) AS AMENDMENT
    FROM
      AE_S_FND_COMMITTED
    WHERE
      (VOIDED IS NULL OR VOIDED <> 'Y')
        AND CHANGE_ORDER_NO IS NOT NULL
        AND CHANGE_ORDER_LINE_ITEM IS NOT NULL
        AND TRANX_TYPE IN ('INTERNAL_WORK')
    GROUP BY
      MULTITENANT_ID,
      AGREEMENT_NO) B ON AE_CP_INT_WORK_AGREE.MULTITENANT_ID = B.MULTITENANT_ID
    AND AE_CP_INT_WORK_AGREE.AGREEMENT_NO = B.AGREEMENT_NO
  LEFT OUTER JOIN (
    SELECT
      MULTITENANT_ID,
      AGREEMENT_NO,
      SUM(EXPENSE_AMOUNT) AS EXPENSED
    FROM
      AE_S_FND_COMMITTED
    WHERE
      (VOIDED IS NULL OR VOIDED <> 'Y')
        AND SOURCE_TRANX_NO IS NOT NULL
        AND TRANX_TYPE IN ('INTERNAL_WORK')
    GROUP BY
      MULTITENANT_ID,
      AGREEMENT_NO) C ON AE_CP_INT_WORK_AGREE.MULTITENANT_ID = C.MULTITENANT_ID
    AND AE_CP_INT_WORK_AGREE.AGREEMENT_NO = C.AGREEMENT_NO
  LEFT OUTER JOIN (
    SELECT
      MULTITENANT_ID,
      AGREEMENT_NO,
      SUM(IWA_AMOUNT + EXPENSE_AMOUNT) * -1.00 AS PO_ENCUMBRANCE
    FROM
      AE_S_FND_COMMITTED
    WHERE
      (VOIDED IS NULL OR VOIDED <> 'Y')
        AND CONTRACT_NO IS NOT NULL
    GROUP BY
      MULTITENANT_ID,
      AGREEMENT_NO) D ON AE_CP_INT_WORK_AGREE.MULTITENANT_ID = D.MULTITENANT_ID
    AND AE_CP_INT_WORK_AGREE.AGREEMENT_NO = D.AGREEMENT_NO;

