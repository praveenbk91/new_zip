);

INSERT INTO AIM_INT_WORK_AGREE_LINE_COST (
  MULTITENANT_ID, AGREEMENT_NO, LINE_ITEM, COMMITMENT, AMENDMENT, EXPENSED, PO_ENCUMBRANCE)
SELECT
  AE_CP_INT_WORK_AGREE_D.MULTITENANT_ID,
  AE_CP_INT_WORK_AGREE_D.AGREEMENT_NO,
  AE_CP_INT_WORK_AGREE_D.LINE_ITEM,
  COALESCE(AE_CP_INT_WORK_AGREE_D.COMMITMENT, 0.0),
  COALESCE(B.AMENDMENT, 0.0),
  COALESCE(C.EXPENSED, 0.0),
  COALESCE(D.PO_ENCUMBRANCE, 0.0)
FROM
  AE_CP_INT_WORK_AGREE_D
  LEFT OUTER JOIN (
    SELECT
      MULTITENANT_ID,
      AGREEMENT_NO,
      AGREEMENT_LINE,
      SUM(AMOUNT) AS AMENDMENT
    FROM
      AE_S_FND_COMMITTED
    WHERE
      (VOIDED IS NULL OR VOIDED <> 'Y')
        AND CHANGE_ORDER_NO IS NOT NULL
        AND CHANGE_ORDER_LINE_ITEM IS NOT NULL
        AND TRANX_TYPE IN ('INTERNAL_WORK')
    GROUP BY
      MULTITENANT_ID,
      AGREEMENT_NO,
      AGREEMENT_LINE) B ON AE_CP_INT_WORK_AGREE_D.MULTITENANT_ID = B.MULTITENANT_ID
    AND AE_CP_INT_WORK_AGREE_D.AGREEMENT_NO = B.AGREEMENT_NO
    AND AE_CP_INT_WORK_AGREE_D.LINE_ITEM = B.AGREEMENT_LINE
  LEFT OUTER JOIN (
    SELECT
      MULTITENANT_ID,
      AGREEMENT_NO,
      AGREEMENT_LINE,
      SUM(EXPENSE_AMOUNT) AS EXPENSED
    FROM
      AE_S_FND_COMMITTED
    WHERE
      (VOIDED IS NULL OR VOIDED <> 'Y')
        AND SOURCE_TRANX_NO IS NOT NULL
        AND TRANX_TYPE IN ('INTERNAL_WORK')
    GROUP BY
      MULTITENANT_ID,
      AGREEMENT_NO,
      AGREEMENT_LINE) C ON AE_CP_INT_WORK_AGREE_D.MULTITENANT_ID = C.MULTITENANT_ID
    AND AE_CP_INT_WORK_AGREE_D.AGREEMENT_NO = C.AGREEMENT_NO
    AND AE_CP_INT_WORK_AGREE_D.LINE_ITEM = C.AGREEMENT_LINE
  LEFT OUTER JOIN (
    SELECT
      MULTITENANT_ID,
      AGREEMENT_NO,
      AGREEMENT_LINE,
      SUM(IWA_AMOUNT + EXPENSE_AMOUNT) * -1.00 AS PO_ENCUMBRANCE
    FROM
      AE_S_FND_COMMITTED
    WHERE
      (VOIDED IS NULL OR VOIDED <> 'Y')
        AND CONTRACT_NO IS NOT NULL
    GROUP BY
      MULTITENANT_ID,
      AGREEMENT_NO,
      AGREEMENT_LINE) D ON AE_CP_INT_WORK_AGREE_D.MULTITENANT_ID = D.MULTITENANT_ID
    AND AE_CP_INT_WORK_AGREE_D.AGREEMENT_NO = D.AGREEMENT_NO
    AND AE_CP_INT_WORK_AGREE_D.LINE_ITEM = D.AGREEMENT_LINE;

UPDATE
  AIM_INT_WORK_AGREE_LINE_COST
SET
  TOTAL = ROUND(COMMITMENT + AMENDMENT, 2),
  REMAINING = ROUND(COMMITMENT + AMENDMENT - EXPENSED - PO_ENCUMBRANCE, 2);
